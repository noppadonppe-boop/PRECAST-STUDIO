import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
const chrome = 'C:/Program Files/Google/Chrome/Application/chrome.exe';
const browser = await chromium.launch({ headless: true, ...(existsSync(chrome) ? { executablePath: chrome } : {}), args: ['--enable-unsafe-swiftshader'] });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('http://localhost:5183/org/org-siam/projects/p-rama9/stages/g0?view=intake');
  await page.getByLabel('นำเข้า IFC', { exact: true }).setInputFiles('Precast_Module_Test.ifc');
  await page.getByRole('heading', { name: '2. ตรวจโมเดล · Precast_Module_Test.ifc' }).waitFor({ timeout: 120000 });
  await page.locator('canvas').waitFor();
  // An untagged file must render a usable reference immediately, before any confirmation.
  const initialCanvas = page.locator('canvas');
  await initialCanvas.scrollIntoViewIfNeeded();
  const initialBounds = await initialCanvas.boundingBox();
  const initialImage = await initialCanvas.screenshot();
  await page.mouse.move(initialBounds.x + initialBounds.width / 2, initialBounds.y + initialBounds.height / 2);
  await page.mouse.down(); await page.mouse.move(initialBounds.x + initialBounds.width / 2 + 90, initialBounds.y + initialBounds.height / 2 + 30, { steps: 8 }); await page.mouse.up();
  if (initialImage.equals(await initialCanvas.screenshot())) throw new Error('Untagged IFC reference is blank or cannot rotate');
  await mkdir('output/bim-intake', { recursive: true });
  await initialCanvas.screenshot({ path: 'output/bim-intake/untagged-reference.png' });
  const referenceToggle = page.getByLabel('แสดงส่วนอื่นจาง ๆ', { exact: false });
  if (!await referenceToggle.isChecked() || !await referenceToggle.isDisabled()) throw new Error('Zero eligible parts can hide the whole model');
  await page.getByRole('button', { name: 'พอดีหน้าจอ', exact: true }).click();
  await page.getByText('รอยืนยันชนิดพรีคาสท์ 5 ชิ้น', { exact: true }).click();
  if (await page.getByRole('button', { name: /เลือกชิ้นงาน #/ }).count()) throw new Error('Unclassified elements became selectable');
  for (let i = 0; i < 5; i++) await page.getByRole('button', { name: /ยืนยันพรีคาสท์ #/ }).first().click();
  if (await page.getByRole('button', { name: /เลือกชิ้นงาน #/ }).count() !== 5) throw new Error('Expected only confirmed structural pieces');
  if (await page.getByRole('button', { name: /เลือกชิ้นงาน #.*(Window|Door|Trim)/ }).count()) throw new Error('Accessory leaked into precast selector');
  await page.getByRole('button', { name: 'มุมมอง แปลน', exact: true }).click();
  await page.getByRole('button', { name: 'มุมมอง 3D', exact: true }).click();
  const selector = page.getByLabel('ชิ้นงานจาก IFC', { exact: false });
  await selector.selectOption({ index: 1 });
  const inspector = page.getByRole('complementary', { name: 'คุณสมบัติชิ้นงาน BIM' });
  await inspector.waitFor();
  const wall = page.getByRole('button', { name: /เลือกชิ้นงาน #.*Basic Wall/ }).first();
  await wall.click();
  if (await wall.getAttribute('aria-pressed') !== 'true') throw new Error('Object strip did not select wall');
  if (await inspector.getByLabel('ชนิดชิ้นงาน', { exact: true }).inputValue() !== 'IfcWallStandardCase') throw new Error('Inspector not synchronized');
  await page.getByRole('button', { name: 'ซ่อนคุณสมบัติ', exact: true }).click();
  if (await inspector.isVisible()) throw new Error('Inspector toggle failed');
  await wall.focus(); await page.keyboard.press('Enter');
  await inspector.waitFor();
  await page.getByRole('button', { name: 'เฉพาะชิ้นที่เลือก', exact: true }).click();
  await page.getByRole('button', { name: 'เฉพาะชิ้นที่เลือก', exact: true }).click();
  const beforeDrag = await selector.inputValue();
  const canvas = page.locator('canvas'); await canvas.scrollIntoViewIfNeeded();
  const bounds = await canvas.boundingBox();
  const beforeRotate = await canvas.screenshot();
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2);
  await page.mouse.down(); await page.mouse.move(bounds.x + bounds.width / 2 + 70, bounds.y + bounds.height / 2 + 30, { steps: 8 }); await page.mouse.up();
  if (await selector.inputValue() !== beforeDrag) throw new Error('Dragging changed selected element');
  if (beforeRotate.equals(await canvas.screenshot())) throw new Error('Mouse drag did not rotate rendered model');
  const beforeZoom = await canvas.screenshot();
  const scrollBefore = await page.evaluate(() => window.scrollY);
  await page.mouse.wheel(0, -350);
  await page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  if (beforeZoom.equals(await canvas.screenshot())) throw new Error('Mouse wheel did not zoom rendered model');
  if (await page.evaluate(() => window.scrollY) !== scrollBefore) throw new Error('Wheel scrolled page instead of zooming');
  await page.getByRole('button', { name: 'พอดีหน้าจอ', exact: true }).click();
  await page.getByRole('button', { name: /เลือกชิ้นงาน #/ }).filter({ hasText: 'IfcSlab' }).first().click();
  const floorId = await selector.inputValue();
  await page.getByLabel('แสดงส่วนอื่นจาง ๆ', { exact: false }).check();
  await canvas.click({ position: { x: bounds.width / 2, y: bounds.height / 2 } });
  if (await selector.inputValue() === floorId) throw new Error('Canvas picking did not update selection');
  if (!['IfcWallStandardCase', 'IfcSlab'].includes(await inspector.getByLabel('ชนิดชิ้นงาน', { exact: true }).inputValue())) throw new Error('Picked a non-precast reference');
  await page.getByLabel('แสดงส่วนอื่นจาง ๆ', { exact: false }).uncheck();
  await page.getByLabel('ค้นหาชิ้นงาน', { exact: true }).fill('no-match-qa');
  await page.getByText('ไม่พบชิ้นงานที่ตรงกับคำค้น', { exact: true }).waitFor();
  await page.getByLabel('ค้นหาชิ้นงาน', { exact: true }).fill('');
  await mkdir('output/bim-intake', { recursive: true });
  await page.evaluate(() => { if (document.activeElement instanceof HTMLElement) document.activeElement.blur(); window.scrollTo(0, 0); });
  await page.screenshot({ path: 'output/bim-intake/intake-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: 'output/bim-intake/intake-mobile.png', fullPage: true });
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  if (overflow) throw new Error('Mobile viewport overflows');
  if (errors.length) throw new Error(errors.join('\n'));
  console.log('PASS: precast-only selection, explicit confirmation, accessories excluded, reference cannot be picked, actual mouse rotation and wheel zoom, no page scroll, 3D/Plan, inspector, mobile.');
} finally { await browser.close(); }
